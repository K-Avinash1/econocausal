"""Exploratory data analysis for the campaign dataset.

compute_eda() works on the observed data alone, and adds a clearly separated
"ground truth" section only when the simulation's truth table is supplied.
Ground truth does not exist for real customer data.
"""
import numpy as np
import pandas as pd

from .schema import (
    COST_COL, NUMERIC_FEATURE_COLS, OUTCOME_COL, REVENUE_COL, TREATMENT_COL,
)


def _smd(treated: pd.Series, control: pd.Series) -> float:
    """Standardised mean difference between two groups."""
    pooled = np.sqrt((treated.var(ddof=1) + control.var(ddof=1)) / 2.0)
    return float((treated.mean() - control.mean()) / pooled) if pooled > 0 else 0.0


def compute_eda(observed: pd.DataFrame, truth: pd.DataFrame = None) -> dict:
    t = observed[TREATMENT_COL] == 1
    y = observed[OUTCOME_COL]
    out = {}

    out["overview"] = {
        "n_rows": int(len(observed)),
        "treated_share": float(t.mean()),
        "purchase_rate": float(y.mean()),
        "purchase_rate_treated": float(y[t].mean()),
        "purchase_rate_untreated": float(y[~t].mean()),
        "naive_difference": float(y[t].mean() - y[~t].mean()),
    }

    cols = list(NUMERIC_FEATURE_COLS)
    out["feature_summary"] = {
        c: {"min": float(observed[c].min()), "mean": float(observed[c].mean()), "max": float(observed[c].max())}
        for c in cols
    }
    out["region_counts"] = {str(k): int(v) for k, v in observed["region"].value_counts().sort_index().items()}

    smd = {c: _smd(observed.loc[t, c], observed.loc[~t, c]) for c in cols}
    for region in sorted(observed["region"].unique()):
        flag = (observed["region"] == region).astype(float)
        smd[f"region={region}"] = _smd(flag[t], flag[~t])
    out["covariate_balance_smd"] = smd

    buyers = observed[observed[OUTCOME_COL] == 1]
    out["money"] = {
        "mean_order_value_treated_buyers": float(buyers.loc[buyers[TREATMENT_COL] == 1, REVENUE_COL].mean()),
        "mean_order_value_untreated_buyers": float(buyers.loc[buyers[TREATMENT_COL] == 0, REVENUE_COL].mean()),
        "total_discount_cost": float(observed[COST_COL].sum()),
        "total_order_value": float(observed[REVENUE_COL].sum()),
    }

    if truth is not None:
        m = observed.merge(truth, on="customer_id", how="inner", validate="one_to_one")
        te = m["true_effect"]
        gt = {
            "true_ate": float(te.mean()),
            "true_att": float(te[m[TREATMENT_COL] == 1].mean()),
            "naive_bias": out["overview"]["naive_difference"] - float(te.mean()),
            "effect_min": float(te.min()),
            "effect_max": float(te.max()),
            "effect_std": float(te.std()),
            "share_negative_effect": float((te < 0).mean()),
            "propensity_min": float(m["true_propensity"].min()),
            "propensity_max": float(m["true_propensity"].max()),
        }
        segments = {}
        segments["loyalty member"] = {
            "no": float(te[m["is_loyalty_member"] == 0].mean()),
            "yes": float(te[m["is_loyalty_member"] == 1].mean()),
        }
        eng = pd.cut(m["email_engagement"], [-0.001, 0.33, 0.66, 1.001], labels=["low (<0.33)", "mid", "high (>0.66)"])
        segments["email engagement"] = {str(k): float(v) for k, v in te.groupby(eng, observed=True).mean().items()}
        rec = pd.cut(m["days_since_last_purchase"], [-1, 14, 60, 10000], labels=["0-14 days", "15-60 days", "60+ days"])
        segments["recency"] = {str(k): float(v) for k, v in te.groupby(rec, observed=True).mean().items()}
        gt["segments"] = segments
        out["ground_truth"] = gt
    return out


def _fmt(x, digits=3):
    return f"{x:.{digits}f}"


def format_eda_markdown(s: dict) -> str:
    o = s["overview"]
    lines = [
        "# Exploratory data analysis",
        "",
        "Generated by `scripts/run_eda.py` from `data/generated/campaign_data.csv`.",
        "Re-run the script to refresh every number below; do not edit by hand.",
        "",
        "## Part A. Observed data (what a real retailer would have)",
        "",
        f"- Customers: **{o['n_rows']:,}**",
        f"- Offered the discount: **{_fmt(o['treated_share'] * 100, 1)}%**",
        f"- Purchase rate overall: **{_fmt(o['purchase_rate'] * 100, 1)}%**",
        f"- Purchase rate, offered: {_fmt(o['purchase_rate_treated'] * 100, 1)}%; not offered: {_fmt(o['purchase_rate_untreated'] * 100, 1)}%",
        f"- Naive difference (offered minus not offered): **{_fmt(o['naive_difference'] * 100, 1)} percentage points**",
        "",
        "The naive difference is NOT the effect of the discount. Customers were not chosen at random (see balance table).",
        "",
        "### Feature summary",
        "",
        "| Feature | Min | Mean | Max |",
        "|---|---|---|---|",
    ]
    for c, v in s["feature_summary"].items():
        lines.append(f"| {c} | {_fmt(v['min'], 2)} | {_fmt(v['mean'], 2)} | {_fmt(v['max'], 2)} |")
    lines += ["", "Region counts: " + ", ".join(f"{k} {v:,}" for k, v in s["region_counts"].items()), "",
              "### Covariate balance (standardised mean difference, offered vs not offered)", "",
              "Values far from 0 (rule of thumb: beyond 0.1) mean the two groups differ on that feature, which is confounding.", "",
              "| Feature | SMD |", "|---|---|"]
    for c, v in s["covariate_balance_smd"].items():
        lines.append(f"| {c} | {_fmt(v, 3)} |")
    m = s["money"]
    lines += ["", "### Money", "",
              f"- Mean order value among buyers, offered: {_fmt(m['mean_order_value_treated_buyers'], 2)}; not offered: {_fmt(m['mean_order_value_untreated_buyers'], 2)} (not a clean comparison: the two groups contain different kinds of customers)",
              f"- Total order value (paid): {_fmt(m['total_order_value'], 0)}; total discount given away: {_fmt(m['total_discount_cost'], 0)}"]
    if "ground_truth" in s:
        g = s["ground_truth"]
        lines += ["", "## Part B. Simulation ground truth (does not exist for real data)", "",
                  "Uses `data/evaluation/ground_truth.csv`. Only for checking that methods recover known effects.", "",
                  f"- True average effect of the discount on purchase probability (ATE): **{_fmt(g['true_ate'] * 100, 2)} percentage points**",
                  f"- True effect among customers who were offered it (ATT): {_fmt(g['true_att'] * 100, 2)} percentage points",
                  f"- Bias of the naive difference (naive minus true ATE): **{_fmt(g['naive_bias'] * 100, 2)} percentage points**",
                  f"- Individual effects range from {_fmt(g['effect_min'] * 100, 2)} to {_fmt(g['effect_max'] * 100, 2)} percentage points (std {_fmt(g['effect_std'] * 100, 2)})",
                  f"- Share of customers with a negative effect: {_fmt(g['share_negative_effect'] * 100, 1)}%",
                  f"- True treatment probability ranges from {_fmt(g['propensity_min'], 2)} to {_fmt(g['propensity_max'], 2)} (overlap holds)",
                  "", "### Average true effect by segment (percentage points)", "",
                  "| Segment | Group | Mean true effect |", "|---|---|---|"]
        for seg, groups in g["segments"].items():
            for name, val in groups.items():
                lines.append(f"| {seg} | {name} | {_fmt(val * 100, 2)} |")
    lines += ["", "## Limits", "",
              "- This is simulated data. Recovering known effects shows the method works under the simulation's assumptions, not that it works on real customers.",
              "- Observed-data checks here do not prove there is no unobserved confounding."]
    return "\n".join(lines) + "\n"

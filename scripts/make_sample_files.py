"""Create small sample CSV files for testing the upload page and the validator.

Writes data/samples/*.csv (one valid file, several deliberately broken ones)
and docs/validation_messages.md, which lists the validator's ACTUAL messages for
each file. The frontend uses those messages as the wording to display.

Run from the project root (virtual environment active):
    python scripts/make_sample_files.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from econocausal.data_generation import generate_campaign_data  # noqa: E402
from econocausal.validation import validate_campaign_data  # noqa: E402

SAMPLES = ROOT / "data" / "samples"


def build_samples():
    observed, _ = generate_campaign_data(n=1000, seed=42)
    s = {}
    s["sample_valid.csv"] = observed.copy()
    s["warning_500_rows.csv"] = observed.iloc[:500].copy()

    d = observed.drop(columns=["discount_offered", "region"])
    s["invalid_missing_columns.csv"] = d

    d = observed.copy()
    d["age"] = d["age"].astype(object)
    d.loc[[3, 17, 42], "age"] = "forty"
    s["invalid_text_in_number.csv"] = d

    # Keep the money columns consistent, so the ONLY problem is missing treatment variation
    d = observed.copy()
    d["discount_offered"] = 1
    d["discount_cost"] = np.round(d["order_value"] * 0.15 / 0.85, 2)
    s["invalid_all_treated.csv"] = d
    d = observed.copy()
    d["discount_offered"] = 0
    d["discount_cost"] = 0.0
    s["invalid_none_treated.csv"] = d

    s["invalid_empty.csv"] = observed.iloc[0:0].copy()
    s["invalid_too_few_rows.csv"] = observed.iloc[:50].copy()

    d = observed.copy(); d.loc[[5, 6, 7, 8, 9], "region"] = "Central"
    s["invalid_bad_region.csv"] = d

    d = observed.copy(); d.loc[10, "customer_id"] = d.loc[9, "customer_id"]
    s["invalid_duplicate_ids.csv"] = d

    d = observed.copy(); d.loc[[2, 4], "email_engagement"] = np.nan
    s["invalid_missing_values.csv"] = d

    d = observed.copy(); d.loc[[11, 12], "is_loyalty_member"] = 2
    s["invalid_not_binary.csv"] = d
    return s


def main():
    SAMPLES.mkdir(parents=True, exist_ok=True)
    samples = build_samples()
    lines = [
        "# Validation messages for the sample files",
        "",
        "Generated by `scripts/make_sample_files.py`. Each row shows what the validator actually reported",
        "for the file in `data/samples/`. The upload page should show these messages to the user.",
        "",
        "| File | Accepted? | Errors | Warnings |",
        "|---|---|---|---|",
    ]
    for name, df in samples.items():
        df.to_csv(SAMPLES / name, index=False)
        reread = pd.read_csv(SAMPLES / name)
        rep = validate_campaign_data(reread)
        errs = "<br>".join(e["message"] for e in rep.errors) or "none"
        warns = "<br>".join(w["message"] for w in rep.warnings) or "none"
        lines.append(f"| `{name}` | {'yes' if rep.ok else 'NO'} | {errs} | {warns} |")
        print(f"{name:<32} accepted={rep.ok}  errors={len(rep.errors)}  warnings={len(rep.warnings)}")
    (ROOT / "docs" / "validation_messages.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote docs/validation_messages.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
